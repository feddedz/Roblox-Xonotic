#!/usr/bin/env python3
"""M1-RTVFS (partial): pack the files the server engine reads at startup into Rojo-syncable modules.

  python3 tools/pk3/pack_runtime.py [--build high]      -> game/generated/vfs/  (run by tools/build.sh)

Contents (what engine/fs.luau's provider needs on Roblox today):
  * the list of every file path of the resolved VFS (FS_Search / exec wildcards need all names),
  * the bytes of every config-kind file (cfg, rc, skin, mapinfo, ...; 660 files, 3 MB) and progs.dat,
    exactly as DarkPlaces opens them (pk3 symlinks resolved, G-031), base64 in modules ≤ 190k chars (D-020).
Runtime side: game/generated/vfs/init.luau returns { files = {...}, load = function(vpath) -> string? },
which is the engine/fs.luau Provider. Server-only (ServerScriptService), never replicated.
Textures, models, sounds and maps are not here: they are Roblox assets or come later (M1-RTVFS).
"""
import argparse
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LIMIT = 180_000  # chars of source per module (D-020: ≤ 190k)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", default="high")
    a = ap.parse_args()
    rows = [l.split("\t") for l in (ROOT / f"assets/manifest/vfs-{a.build}.tsv").read_text().splitlines()
            if l and not l.startswith("#")]
    names = [r[0] for r in rows]
    pk3s = sorted({r[2] for r in rows})
    pack_of = "".join(chr(48 + pk3s.index(r[2])) for r in rows)  # one char per name, same order
    want = [r[0] for r in rows if r[1] == "config" or r[0] == "progs.dat"]
    out = ROOT / "game/generated/vfs"
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("*.luau"):
        old.unlink()
    mods: list[str] = []

    def emit(prefix: str, body_lines: list[str]) -> None:
        name = f"{prefix}{len([m for m in mods if m.startswith(prefix)]):03d}"
        (out / f"{name}.luau").write_text("-- GENERATED by tools/pk3/pack_runtime.py. Do not edit.\nreturn {\n"
                                          + "\n".join(body_lines) + "\n}\n")
        mods.append(name)

    # file names
    cur, size = [], 0
    for n in names:
        line = f'\t"{n}",'
        if size + len(line) > LIMIT and cur:
            emit("n", cur)
            cur, size = [], 0
        cur.append(line)
        size += len(line) + 1
    if cur:
        emit("n", cur)
    # which pk3 each name comes from (FS_WhichPack): pack list + one index char per name
    body = ["\tpacks = true,", "\t" + ", ".join(f'"{p}"' for p in pk3s) + ","]
    for i in range(0, len(pack_of), LIMIT // 2):
        body.append(f'\t{{ "", "{pack_of[i:i + LIMIT // 2]}" }},')
    emit("p", body)
    # file data: base64 pieces; a big file spans several modules (pieces joined in order)
    cur, size = [], 0
    for v in want:
        b64 = base64.b64encode((ROOT / f"work/vfs-{a.build}" / v).read_bytes()).decode()
        for i in range(0, max(len(b64), 1), LIMIT // 2):
            piece = b64[i : i + LIMIT // 2]
            line = f'\t{{ "{v}", "{piece}" }},'
            if size + len(line) > LIMIT and cur:
                emit("d", cur)
                cur, size = [], 0
            cur.append(line)
            size += len(line) + 1
    if cur:
        emit("d", cur)
    req = "\n".join(f'\trequire("@self/{m}"),' for m in mods)
    (out / "init.luau").write_text(f'''--!strict
-- GENERATED by tools/pk3/pack_runtime.py from assets/manifest/vfs-{a.build}.tsv. Do not edit.
-- engine/fs.luau Provider on Roblox: every VFS path + the bytes of config files and progs.dat.
local parts = {{
{req}
}}
local files: {{ string }} = {{}}
local b64: {{ [string]: {{ string }} }} = {{}}
local packnames: {{ string }} = {{}}
local packidx: {{ string }} = {{}}
for _, p in parts do
	if (p :: any).packs then
		for _, e in (p :: any) do
			if type(e) == "string" then
				table.insert(packnames, e)
			elseif type(e) == "table" then
				table.insert(packidx, e[2])
			end
		end
		continue
	end
	for _, e in p :: any do
		if type(e) == "string" then
			table.insert(files, e)
		else
			local t = b64[e[1]] or {{}}
			b64[e[1]] = t
			table.insert(t, e[2])
		end
	end
end
local A = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
local rev = {{}}
for i = 1, 64 do
	rev[string.byte(A, i)] = i - 1
end
local function decode(s: string): string
	local n = #s
	local pad = (if string.sub(s, -2) == "==" then 2 elseif string.sub(s, -1) == "=" then 1 else 0)
	local out = buffer.create(n // 4 * 3 - pad)
	local o = 0
	for i = 1, n, 4 do
		local a, b, c, d = string.byte(s, i, i + 3)
		local v = rev[a] * 262144 + rev[b] * 4096 + (rev[c] or 0) * 64 + (rev[d] or 0)
		buffer.writeu8(out, o, v // 65536)
		if o + 1 < buffer.len(out) then
			buffer.writeu8(out, o + 1, (v // 256) % 256)
		end
		if o + 2 < buffer.len(out) then
			buffer.writeu8(out, o + 2, v % 256)
		end
		o += 3
	end
	return buffer.tostring(out)
end
local packof: {{ [string]: string }}? = nil
local cache: {{ [string]: string }} = {{}}
return {{
	files = files,
	load = function(vpath: string): string?
		local c = cache[vpath]
		if c then
			return c
		end
		local p = b64[vpath]
		if not p then
			return nil
		end
		c = decode(table.concat(p))
		cache[vpath] = c
		return c
	end,
	-- FS_WhichPack: pk3 file name of the file DarkPlaces opens (nil if not in a pack)
	pack = function(vpath: string): string?
		if not packof then
			local m: {{ [string]: string }} = {{}}
			local idx = table.concat(packidx)
			for i, f in files do
				m[f] = packnames[string.byte(idx, i) - 47]
			end
			packof = m
		end
		return (packof :: any)[vpath]
	end,
}}
''')
    total = sum((out / f"{m}.luau").stat().st_size for m in mods)
    print(f"packed {len(names)} names, {len(want)} files into {len(mods)} modules ({total / 1e6:.1f} MB) -> {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
