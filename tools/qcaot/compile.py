#!/usr/bin/env python3
"""QuakeC bytecode -> Luau ahead-of-time compiler (task M2-AOT, docs/subsystems/qcvm.md).

One Luau function per QC function, semantics identical to the reference interpreter
engine/prvm_exec.luau (= prvm_execprogram.h @xonotic-v0.8.6):
  * all QC data stays in the prog's buffers (globals; locals are global slots saved by
    PRVM_EnterFunction), so float32 rounding happens on every store exactly as in C (D-004);
  * calls, returns, edict loads/stores and the runaway counter go through engine/_port/qcrt.luau,
    which shares code paths and error text with the interpreter.
Control flow (v1): basic blocks + a `pc` dispatch loop (binary if-tree), valid for every CFG including
the 3 irreducible functions. Structured output for reducible CFGs is task M2-AOT-STRUCT (performance only).

Usage: python3 tools/qcaot/compile.py work/vfs-high/progs.dat game/generated/progs [--chunk-statements N]
Output: <out>/init.luau (returns install(prog)) + <out>/c<NNN>.luau chunks. Regenerable; never hand-edit.
"""
from __future__ import annotations

import argparse, hashlib, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from progs import OP, OPS, Progs, load  # noqa: E402
from cfg import build_cfg  # noqa: E402

HEADER = """--!nocheck
--!nolint
-- GENERATED by tools/qcaot/compile.py from {src} (sha256 {sha}). DO NOT EDIT.
-- Xonotic QuakeC (GPLv2+ / GPLv3+, Team Xonotic) compiled to Luau; see docs/subsystems/qcvm.md.
local qcrt = require("../../../engine/_port/qcrt")
local rf, wf, ri, wi = buffer.readf32, buffer.writef32, buffer.readi32, buffer.writei32
local fround = require("../../../engine/_port/f32").round
local band, bor = bit32.band, bit32.bor
local istrue, ftoi, tosigned = qcrt.istrue, qcrt.ftoi, qcrt.tosigned
local GetString, strcmp = qcrt.GetString, qcrt.strcmp
local call, ret, jump = qcrt.call, qcrt.ret, qcrt.jump
local load1, loadv, address, storep1, storepv = qcrt.load1, qcrt.loadv, qcrt.address, qcrt.storep1, qcrt.storepv
local F = {{}}
"""

STORE_OPS = {OP[n] for n in ("STORE_F", "STORE_ENT", "STORE_FLD", "STORE_S", "STORE_FNC")}
STOREP_OPS = {OP[n] for n in ("STOREP_F", "STOREP_ENT", "STOREP_FLD", "STOREP_S", "STOREP_FNC")}
LOAD_OPS = {OP[n] for n in ("LOAD_F", "LOAD_FLD", "LOAD_ENT", "LOAD_S", "LOAD_FNC")}
CALL_OPS = {OP[f"CALL{i}"]: i for i in range(9)}

CMP = {"GE": ">=", "LE": "<=", "GT": ">", "LT": "<", "EQ_F": "==", "NE_F": "~="}
ARITH = {"ADD_F": "+", "SUB_F": "-", "MUL_F": "*"}
VARITH = {"ADD_V": "+", "SUB_V": "-"}


def operands(op: int, a: int, b: int, c: int):
    """Operand slots as PRVM_Prog_Load stores them (statements group switch)."""
    return a, b, c


def emit_statement(p: Progs, i: int) -> list[str]:
    """Luau lines for statement i, except control flow (IF/IFNOT/GOTO/RETURN/DONE handled by caller)."""
    s = p.statements[i]
    op = s.op
    name = OPS[op]
    A, B, C = s.a * 4, s.b * 4, s.c * 4
    if name in ARITH:
        return [f"wf(G, {C}, rf(G, {A}) {ARITH[name]} rf(G, {B}))"]
    if name in VARITH:
        o = VARITH[name]
        return [f"wf(G, {C + 4 * k}, rf(G, {A + 4 * k}) {o} rf(G, {B + 4 * k}))" for k in range(3)]
    if name == "MUL_V":
        return [f"wf(G, {C}, fround(fround(fround(rf(G, {A}) * rf(G, {B})) + fround(rf(G, {A + 4}) * rf(G, {B + 4})))"
                f" + fround(rf(G, {A + 8}) * rf(G, {B + 8}))))"]
    if name == "MUL_FV":
        return ["do", f"\tlocal t = rf(G, {A})"] + [f"\twf(G, {C + 4 * k}, t * rf(G, {B + 4 * k}))" for k in range(3)] + ["end"]
    if name == "MUL_VF":
        return ["do", f"\tlocal t = rf(G, {B})"] + [f"\twf(G, {C + 4 * k}, t * rf(G, {A + 4 * k}))" for k in range(3)] + ["end"]
    if name == "DIV_F":
        return ["do", f"\tlocal d = rf(G, {B})", "\tif d ~= 0 then", f"\t\twf(G, {C}, rf(G, {A}) / d)", "\telse",
                f"\t\tqcrt.divzero(prog, {i})", f"\t\twf(G, {C}, 0)", "\tend", "end"]
    if name == "BITAND":
        return [f"wf(G, {C}, tosigned(band(ftoi(rf(G, {A})), ftoi(rf(G, {B})))))"]
    if name == "BITOR":
        return [f"wf(G, {C}, tosigned(bor(ftoi(rf(G, {A})), ftoi(rf(G, {B})))))"]
    if name in CMP:
        return [f"wf(G, {C}, if rf(G, {A}) {CMP[name]} rf(G, {B}) then 1 else 0)"]
    if name == "AND":
        return [f"wf(G, {C}, if istrue(ri(G, {A})) and istrue(ri(G, {B})) then 1 else 0)"]
    if name == "OR":
        return [f"wf(G, {C}, if istrue(ri(G, {A})) or istrue(ri(G, {B})) then 1 else 0)"]
    if name == "NOT_F":
        return [f"wf(G, {C}, if istrue(ri(G, {A})) then 0 else 1)"]
    if name == "NOT_V":
        return [f"wf(G, {C}, if rf(G, {A}) == 0 and rf(G, {A + 4}) == 0 and rf(G, {A + 8}) == 0 then 1 else 0)"]
    if name == "NOT_S":
        return ["do", f"\tlocal s = ri(G, {A})", f"\twf(G, {C}, if s == 0 or GetString(prog, s) == \"\" then 1 else 0)", "end"]
    if name in ("NOT_FNC", "NOT_ENT"):
        return [f"wf(G, {C}, if ri(G, {A}) == 0 then 1 else 0)"]
    if name == "EQ_V":
        return [f"wf(G, {C}, if rf(G, {A}) == rf(G, {B}) and rf(G, {A + 4}) == rf(G, {B + 4}) and rf(G, {A + 8}) == rf(G, {B + 8}) then 1 else 0)"]
    if name == "NE_V":
        return [f"wf(G, {C}, if rf(G, {A}) ~= rf(G, {B}) or rf(G, {A + 4}) ~= rf(G, {B + 4}) or rf(G, {A + 8}) ~= rf(G, {B + 8}) then 1 else 0)"]
    if name == "EQ_S":
        return [f"wf(G, {C}, if strcmp(GetString(prog, ri(G, {A})), GetString(prog, ri(G, {B}))) == 0 then 1 else 0)"]
    if name == "NE_S":
        return [f"wf(G, {C}, strcmp(GetString(prog, ri(G, {A})), GetString(prog, ri(G, {B}))))"]
    if name in ("EQ_E", "EQ_FNC"):
        return [f"wf(G, {C}, if ri(G, {A}) == ri(G, {B}) then 1 else 0)"]
    if name in ("NE_E", "NE_FNC"):
        return [f"wf(G, {C}, if ri(G, {A}) ~= ri(G, {B}) then 1 else 0)"]
    if op in STORE_OPS:
        return [f"wi(G, {B}, ri(G, {A}))"]
    if name == "STORE_V":
        return [f"wi(G, {B + 4 * k}, ri(G, {A + 4 * k}))" for k in range(3)]
    if op in STOREP_OPS:
        return [f"storep1(prog, {A}, {B}, {i})"]
    if name == "STOREP_V":
        return [f"storepv(prog, {A}, {B}, {i})"]
    if name == "ADDRESS":
        return [f"address(prog, {A}, {B}, {C}, {i})"]
    if op in LOAD_OPS:
        return [f"load1(prog, {A}, {B}, {C}, {i})"]
    if name == "LOAD_V":
        return [f"loadv(prog, {A}, {B}, {C}, {i})"]
    if op in CALL_OPS:
        return [f"call(prog, ri(G, {A}), {CALL_OPS[op]}, {i})"]
    if name == "STATE":
        return [f"prog.error_cmd(string.format(\"OP_STATE not supported by %s\", prog.name))"]
    raise ValueError(f"unhandled opcode {name} at {i}")


def compile_function(p: Progs, f) -> list[str]:
    c = build_cfg(p, f)
    st = p.statements
    blocks = [k for k in range(len(c.blocks)) if k in c.reachable]
    # straight-line code only when there is one block and it never jumps (a self-loop needs the dispatch loop)
    single = len(blocks) == 1 and not c.succ[blocks[0]]
    out = [f"F[{f.index}] = function(prog) -- qc: {f.name} s{c.start}-{c.end}", "\tlocal G = prog.globals"]

    def block_lines(k: int) -> list[str]:
        lines = []
        first, last = c.blocks[k], c.block_end(k)
        for i in range(first, last + 1):
            s = st[i]
            n = OPS[s.op]
            if n in ("RETURN", "DONE"):
                lines += [f"ret(prog, {s.a * 4}, {i})", "return"]
                return lines
            if n == "GOTO":
                lines += [f"jump(prog, {i})", f"pc = {c.blocks.index(s.jump)}", "continue"]
                return lines
            if n in ("IF", "IFNOT"):
                cond = f"istrue(ri(G, {s.a * 4}))" if n == "IF" else f"not istrue(ri(G, {s.a * 4}))"
                lines += [f"if {cond} then", f"\tjump(prog, {i})", f"\tpc = {c.blocks.index(s.jump)}", "\tcontinue", "end"]
                continue  # falls through to the next statement (block ends here: leader follows)
            lines += emit_statement(p, i)
        # fell off the block end into the next leader
        if single:
            raise ValueError(f"{f.name}: single block without terminator")
        lines += [f"pc = {k + 1}"]
        return lines

    if single:
        out += ["\t" + l for l in block_lines(blocks[0])]
    else:
        out += ["\tlocal pc = 0", "\twhile true do"]

        def tree(ids: list[int], depth: int) -> list[str]:
            ind = "\t" * depth
            if len(ids) == 1:
                return [ind + l for l in block_lines(ids[0])]
            mid = len(ids) // 2
            return ([f"{ind}if pc < {ids[mid]} then"] + tree(ids[:mid], depth + 1) + [f"{ind}else"]
                    + tree(ids[mid:], depth + 1) + [f"{ind}end"])

        out += tree(blocks, 2)
        out += ["\tend"]
    out += ["end"]
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("progs")
    ap.add_argument("out")
    ap.add_argument("--chunk-statements", type=int, default=20000)
    a = ap.parse_args()
    src = Path(a.progs)
    sha = hashlib.sha256(src.read_bytes()).hexdigest()
    p = load(src)
    outdir = Path(a.out)
    outdir.mkdir(parents=True, exist_ok=True)
    for old in outdir.glob("c*.luau"):
        old.unlink()
    qc = [f for f in p.functions if f.builtin is None and f.index > 0]
    chunks, cur, cur_n = [], [], 0
    for f in qc:
        c = build_cfg(p, f)
        n = c.end - c.start + 1
        if cur and cur_n + n > a.chunk_statements:
            chunks.append(cur)
            cur, cur_n = [], 0
        cur.append(f)
        cur_n += n
    if cur:
        chunks.append(cur)
    total = 0
    for ci, fs in enumerate(chunks):
        lines = [HEADER.format(src=src.name, sha=sha).rstrip("\n")]
        for f in fs:
            lines += compile_function(p, f)
        lines.append("return F")
        text = "\n".join(lines) + "\n"
        total += len(text)
        (outdir / f"c{ci:03d}.luau").write_text(text)
    init = [
        "--!strict",
        f"-- GENERATED by tools/qcaot/compile.py from {src.name} (sha256 {sha}). DO NOT EDIT.",
        "-- install(prog): registers every compiled QC function in prog.aot (see engine/_port/qcrt.luau).",
        "local chunks = {",
    ] + [f"\trequire(\"@self/c{ci:03d}\")," for ci in range(len(chunks))] + [
        "}",
        "return {",
        f"\tsha256 = \"{sha}\",",
        f"\tnumfunctions = {len(p.functions)},",
        "\tinstall = function(prog: any)",
        "\t\tfor _, F in chunks do",
        "\t\t\tfor fnum, fn in F do",
        "\t\t\t\tprog.aot[fnum] = fn",
        "\t\t\tend",
        "\t\tend",
        "\tend,",
        "}",
    ]
    (outdir / "init.luau").write_text("\n".join(init) + "\n")
    print(f"{src}: {len(qc)} functions -> {len(chunks)} chunks, {total / 1e6:.1f} MB Luau", file=sys.stderr)


if __name__ == "__main__":
    main()
