#!/usr/bin/env python3
"""Generate Luau data tables that are direct transcriptions of DarkPlaces C data (@xonotic-v0.8.6):

  engine/prvm_offsets.luau       <- prvm_offsets.h (PRVM_DECLARE_* lists, file order) as used by
                                    sv_main.c sv_reqfields/sv_reqglobals, cl_main/csprogs.c, menu.c
  engine/_port/builtin_names.luau <- vm_sv_builtins[] (svvm_cmds.c), vm_cl_builtins[] (clvm_cmds.c),
                                    vm_m_builtins[] (mvm_cmds.c): builtin number -> C function name

Usage: python3 tools/engine/gen_tables.py [darkplaces source dir]
(default work/source/Xonotic/source/darkplaces, from tools/release/fetch.sh source)
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "work/source/Xonotic/source/darkplaces"
if not (src / "prvm_offsets.h").exists():
    alt = ROOT / "work/release-standard/Xonotic/source/darkplaces"
    src = alt if (alt / "prvm_offsets.h").exists() else sys.exit(f"no darkplaces source at {src}")

ETYPE = {"float": 2, "vector": 3, "string": 1, "edict": 4, "function": 6}
decls = re.findall(r"^PRVM_DECLARE_(\w+)\((\w+)\)", (src / "prvm_offsets.h").read_text(), re.M)
groups = {}
for kind, name in decls:
    groups.setdefault(kind, []).append(name)


def lua_list(kind):
    m = re.match(r"(server|client|menu)(field|global)(float|vector|string|edict|function)$", kind)
    return m


out = ["--!strict", "-- GENERATED by tools/engine/gen_tables.py from prvm_offsets.h @xonotic-v0.8.6. DO NOT EDIT.",
       "-- Required fields/globals appended by PRVM_Prog_Load (sv_main.c sv_reqfields/sv_reqglobals and the",
       "-- client/menu equivalents), in prvm_offsets.h order. type: 1 string, 2 float, 3 vector, 4 entity, 6 function.",
       "local M = {}"]
for vm in ("server", "client", "menu"):
    for what in ("field", "global"):
        entries = [(ETYPE[t], n) for kind, n in decls
                   if (m := re.match(rf"{vm}{what}(float|vector|string|edict|function)$", kind)) for t in [m.group(1)]]
        out.append(f"M.{vm}_{what}s = {{")
        out += [f"\t{{ type = {t}, name = \"{n}\" }}," for t, n in entries]
        out.append("}")
for kind in ("field", "global", "function"):
    out.append(f"-- engine-known names (PRVM_DECLARE_{kind}), looked up by name after loading")
    out.append(f"M.known_{kind}s = {{ " + ", ".join(f"\"{n}\"" for n in groups.get(kind, [])) + " }")
out.append("return M")
(ROOT / "engine/prvm_offsets.luau").write_text("\n".join(out) + "\n")


def builtins(cfile, table):
    text = (src / cfile).read_text(errors="replace")
    body = re.search(rf"prvm_builtin_t {table}\[\] = \{{(.*?)\n\}};", text, re.S).group(1)
    names = []
    for line in body.splitlines():
        m = re.match(r"\s*(NULL|\w+)\s*,", line)
        if m:
            names.append(None if m.group(1) == "NULL" else m.group(1))
    return names


out = ["--!strict", "-- GENERATED by tools/engine/gen_tables.py from svvm_cmds.c / clvm_cmds.c / mvm_cmds.c @xonotic-v0.8.6.",
       "-- DO NOT EDIT. index = builtin number + 1; false = NULL entry. numbuiltins = #list.", "local M = {}"]
for key, cfile, table in (("sv", "svvm_cmds.c", "vm_sv_builtins"), ("cl", "clvm_cmds.c", "vm_cl_builtins"),
                          ("m", "mvm_cmds.c", "vm_m_builtins")):
    names = builtins(cfile, table)
    out.append(f"M.{key} = {{ -- {table}, {len(names)} entries, {sum(1 for n in names if n)} non-NULL")
    for i in range(0, len(names), 8):
        out.append("\t" + " ".join(("false," if n is None else f"\"{n}\",") for n in names[i:i + 8]))
    out.append("}")
out.append("return M")
(ROOT / "engine/_port/builtin_names.luau").write_text("\n".join(out) + "\n")
print("ok:", {k: len(v) for k, v in groups.items() if k.startswith("server")})
